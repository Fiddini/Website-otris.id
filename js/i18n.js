  const storageKey = 'otris-language';
  const defaultLanguage = 'id';
  const translatedAttributes = ['alt', 'aria-label', 'content', 'placeholder', 'title'];
  const validLanguage = value => Object.hasOwn(dictionaries, value);

  function readLanguage() {
    try {
      const saved = localStorage.getItem(storageKey);
      if (validLanguage(saved)) return saved;
      if (saved !== null) localStorage.removeItem(storageKey);
      return defaultLanguage;
    } catch {
      return defaultLanguage;
    }
  }

  let language = readLanguage();

  function translate(key) {
    return dictionaries[language][key] ?? dictionaries[defaultLanguage][key] ?? key;
  }

  function apply(root = document) {
    const textSelector = '[data-i18n]';
    const nodes = root.matches?.(textSelector)
      ? [root, ...root.querySelectorAll(textSelector)]
      : root.querySelectorAll(textSelector);
    for (const node of nodes) {
      node.textContent = translate(node.dataset.i18n);
    }
    for (const attribute of translatedAttributes) {
      const source = 'data-i18n-' + attribute;
      const selector = '[' + source + ']';
      const elements = root.matches?.(selector)
        ? [root, ...root.querySelectorAll(selector)]
        : root.querySelectorAll(selector);
      for (const element of elements) {
        element.setAttribute(attribute, translate(element.getAttribute(source)));
      }
    }
  }

  function updatePage() {
    document.documentElement.lang = language;
    apply();
    for (const button of document.querySelectorAll('.language-switch [data-language]')) {
      button.setAttribute('aria-pressed', String(button.dataset.language === language));
    }
  }

  function setLanguage(next) {
    if (!validLanguage(next)) return;
    const changed = next !== language;
    language = next;
    try {
      localStorage.setItem(storageKey, language);
    } catch {
      // The current page can still switch languages when storage is disabled.
    }
    if (!changed) return;
    updatePage();
    document.dispatchEvent(new CustomEvent('otris:languagechange', { detail: { language } }));
  }

  window.otrisI18n = Object.freeze({ get language() { return language; }, translate, apply, setLanguage });
  updatePage();
  for (const button of document.querySelectorAll('.language-switch [data-language]')) {
    button.addEventListener('click', () => setLanguage(button.dataset.language));
  }
